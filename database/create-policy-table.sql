-- Purpose:
-- Create the procurement policy table.
-- Execute this script once.

CREATE COLUMN TABLE PROCUREMENT_POLICIES (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY,
    POLICY_ID NVARCHAR(10) NOT NULL,
    POLICY_NAME NVARCHAR(100) NOT NULL,
    POLICY_TEXT NCLOB NOT NULL,

    PRIMARY KEY (ID)
);

-- Verify table contents
SELECT
    ID,
    POLICY_ID,
    POLICY_NAME,
    POLICY_TEXT
FROM PROCUREMENT_POLICIES
ORDER BY ID;

-- Verify policy count
SELECT COUNT(*) AS POLICY_COUNT
FROM PROCUREMENT_POLICIES;